/// <summary>
/// A ticket that needs attention, with the signals <see cref="AttentionPolicy"/> found for it.
/// The list arrives already ranked by <see cref="AttentionPolicy.Rank"/> (ATTN-RULE-04) — the page
/// renders the given order and applies no ordering of its own.
/// </summary>
public sealed record AttentionListItem(
    int Id,
    string Reference,
    string Title,
    Priority Priority,
    Status Status,
    string TeamName,
    string? AssigneeDisplayName,
    TicketSlaView Sla,
    IReadOnlyList<AttentionSignalView> Signals)
{
    /// <summary>The most severe signal on this ticket — what put it where it is in the ranking.</summary>
    public AttentionSeverity HighestSeverity => Signals.Max(s => s.Severity);
}

