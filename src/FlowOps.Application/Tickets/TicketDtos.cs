/// <summary>
/// Which source table a <see cref="TicketTimelineEntry"/> was projected from. A presentation-layer
/// distinction only — it exists to disambiguate the merged timeline's two id sequences (an event
/// id and a comment id are not comparable) and to tell the view which fields are populated. It is
/// not a business rule: AUDIT-RULE-06 requires events and comments to stay stored and queried
/// separately and to merge only for display, and this enum is how that merge is represented.
/// </summary>
public enum TicketTimelineEntryKind
{
    /// <summary>Ordered before <see cref="Comment"/> as this type's tiebreak default — an
    /// arbitrary but fixed choice, not a documented rule.</summary>
    Event,
    Comment,
}

/// <summary>
/// One row of a ticket's merged activity timeline (AUDIT-RULE-06): either a <c>TicketEvent</c>
/// (audit, AUDIT-RULE-01/02) or a <c>TicketComment</c> (human operational content, TICKET-ENT-05),
/// flattened into one explicit shape rather than exposed as two entity types or as <c>object</c>.
/// Event-only and comment-only fields are populated according to <see cref="Kind"/>; the two
/// source tables remain distinct entities and distinct queries — only this presentation record
/// merges them.
/// </summary>
/// <param name="Id">The source row's own id. Not unique across kinds — always pair with
/// <see cref="Kind"/> when identifying an entry (e.g. as a Razor <c>@key</c>).</param>
/// <param name="OccurredAt">The event's <c>OccurredAt</c> or the comment's <c>CreatedAt</c> —
/// the timeline's primary ordering key.</param>
/// <param name="EventType">Set only when <see cref="Kind"/> is <see cref="TicketTimelineEntryKind.Event"/>.</param>
/// <param name="Field">Set only for field-change events.</param>
/// <param name="Body">Set only when <see cref="Kind"/> is <see cref="TicketTimelineEntryKind.Comment"/>.</param>
/// <param name="IsInternal">Set only for comments (TICKET-ENT-05). Never <c>true</c> in a result
/// handed to a caller <see cref="TicketAccessPolicy.CanSeeInternalComments"/> denies — that
/// exclusion happens in the query that builds this list, not here.</param>
public sealed record TicketTimelineEntry(
    TicketTimelineEntryKind Kind,
    int Id,
    DateTimeOffset OccurredAt,
    string ActorDisplayName,
    TicketEventType? EventType,
    string? Field,
    string? OldValue,
    string? NewValue,
    string? Note,
    string? Body,
    bool? IsInternal);

/// <summary>
/// One page of results plus the totals a pager needs. <paramref name="TotalCount"/> is the count
/// of rows the caller is authorized to see, not the table total — the same authorization scope is
/// applied to the count query as to the page query.
/// </summary>
public sealed record PagedResult<T>(IReadOnlyList<T> Items, int PageNumber, int PageSize, int TotalCount)
{
    public int TotalPages => TotalCount == 0 ? 1 : (int)Math.Ceiling(TotalCount / (double)PageSize);

    public bool HasPreviousPage => PageNumber > 1;

    public bool HasNextPage => PageNumber < TotalPages;
}

