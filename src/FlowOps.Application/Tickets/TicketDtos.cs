/// <summary>
/// SLA Compliance (CLAUDE.md §22), computed over the 90-day reporting window. Counts the
/// persisted <see cref="Ticket.SlaMet"/> fact directly (SLA-RULE-08) — this is aggregation of an
/// already-decided outcome, not a re-derivation of SLA status, so it does not duplicate
/// <see cref="SlaPolicy"/>.
/// </summary>
/// <param name="MetCount">Qualifying tickets where <c>SlaMet == true</c>.</param>
/// <param name="QualifyingCount">All qualifying tickets — resolved in the window, with a
/// non-null <c>SlaMet</c> (a reopened-and-not-yet-resolved-again ticket has neither and does not
/// count here — SLA-RULE-09 intentionally does not preserve a prior cycle's outcome).</param>
public sealed record SlaComplianceSummary(int MetCount, int QualifyingCount)
{
    /// <summary>Null — not <c>0</c>, not <c>NaN</c> — when no ticket qualifies. An honest
    /// "no data yet" rather than a fabricated percentage (CLAUDE.md §21.9's review checklist).</summary>
    public double? Percentage => QualifyingCount == 0 ? null : 100.0 * MetCount / QualifyingCount;
}

/// <summary>
/// Average Resolution Time (CLAUDE.md §22): the mean of <c>ResolvedAt − SlaStartedAt</c> over
/// tickets resolved in the 90-day window. <c>SlaStartedAt</c>, not <c>CreatedAt</c>, so a
/// reopened ticket's average reflects only its current cycle — consistent with every other
/// SLA-adjacent calculation in the system already being cycle-scoped (SLA-RULE-03/07/09), and
/// with the fact that <c>CreatedAt</c> would otherwise silently fold a prior, already-measured
/// cycle's duration into a number meant to describe only the latest one.
/// </summary>
/// <param name="Average">Null when <paramref name="SampleCount"/> is zero.</param>
public sealed record ResolutionTimeSummary(TimeSpan? Average, int SampleCount);

/// <summary>
/// One row of the current workload distribution (§3.3, "Analytics... owns... workload"; §1,
/// "Who on my team is overloaded?"): how many currently open tickets sit with one assignee (or
/// unassigned) on one team, within the caller's <see cref="AnalyticsScope"/>. Deliberately just a
/// count, not the optional ATTN-RULE-07 weighted score (not built in Phase 10).
/// </summary>
public sealed record WorkloadItem(
    int TeamId,
    string TeamName,
    Guid? AssigneeId,
    string? AssigneeDisplayName,
    int OpenTicketCount);

/// <summary>
/// The Phase 10 dashboard's exactly-four KPIs (CLAUDE.md §22) plus the workload distribution.
